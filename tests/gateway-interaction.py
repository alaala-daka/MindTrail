from playwright.sync_api import sync_playwright, expect
with sync_playwright() as p:
    browser = p.chromium.launch(channel='msedge', headless=True)
    page = browser.new_page(viewport={'width':1440,'height':900})
    page.goto('http://127.0.0.1:1439/tests/gateway-harness.html')
    real = page.get_by_role('button', name='真实认证任务')
    expect(real).to_be_visible()
    real.click()
    expect(page.locator('.badge')).to_have_text('真实任务')
    expect(real).to_contain_text('已完成')
    page.locator('[data-node-id="login-api"]').click()
    expect(page.locator('.facts')).to_contain_text('真实任务独有证据')
    real.click()
    expect(page.locator('[data-node-id="login-api"]')).to_have_attribute('aria-pressed', 'true')
    expect(page.locator('.facts')).to_contain_text('真实任务独有证据')
    page.get_by_role('button', name='调用视图').click()
    page.locator('[data-node-id="login-api"]').focus()
    expect(page.locator('[data-node-id="login-api"]')).to_be_focused()
    page.evaluate('window.dispatchEvent(new Event("focus"))')
    expect(page.locator('[data-node-id="login-api"]')).to_have_attribute('aria-pressed', 'true')
    expect(page.locator('[data-node-id="login-api"]')).to_be_focused()
    page.get_by_role('button', name='实现用户认证').click()
    expect(page.locator('.badge')).to_have_text('内置样例')
    expect(page.locator('.facts')).not_to_contain_text('真实任务独有证据')
    browser.close()
    print('PASS real task switch, repeat selection, focus refresh and demo isolation', flush=True)

